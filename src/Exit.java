/**
 * Class to represent the exit to a floor of the dungeon
 */
public class Exit implements GameElement
{
    /**
     * Constructor ccontains nothing
     */
    public Exit()
    {

    }

    /**
     * toString to represent the exit as "EXIT"
     * @return "EXIT"
     */
    public String toString()
    {
        return "EXIT";
    }
}
